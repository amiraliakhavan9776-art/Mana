async function serve(t,runner){
 const s=start({runner,missionSelection:true});await once(s,'listening');
 const close=()=>new Promise((resolve,reject)=>s.close(e=>e?reject(e):resolve()));
 t.after(()=>{if(s.listening)return close();});
 const url='http://127.0.0.1:'+s.address().port;
 const html=await (await fetch(url)).text();
 assert.equal(s.address().address,'127.0.0.1');
 assert.match(html,/<html lang="fa" dir="rtl"/);
 assert(html.includes(command));
 const token=html.match(/'X-Mana-Token':'([0-9a-f]{64})'/)[1];
 const headers={origin:url,'x-mana-token':token,'content-type':'application/json'};
 return {url,html,close,go:(instruction=command,override={})=>fetch(url+'/run',{method:'POST',headers:{...headers,...override},body:JSON.stringify({instruction})}),history:()=>fetch(url+'/history')};
}
const nextTick=()=>new Promise(resolve=>setImmediate(resolve));
